let currentLang = 'pt';
function t(key) { return (i18n[currentLang] && i18n[currentLang][key]) ? i18n[currentLang][key] : key; }

function applyLang() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (k && i18n[currentLang] && i18n[currentLang][k]) el.textContent = i18n[currentLang][k];
  });
  const label = document.getElementById('lang-label');
  if (label) label.textContent = currentLang === 'pt' ? 'EN' : 'PT';
}

function saveLang() { try { localStorage.setItem('kaell_portfolio_lang', currentLang); } catch (e) {} }
function loadLang() {
  try {
    const saved = localStorage.getItem('kaell_portfolio_lang');
    if (saved === 'en' || saved === 'pt') currentLang = saved;
  } catch (e) {}
  applyLang();
}

function switchLang() {
  currentLang = currentLang === 'pt' ? 'en' : 'pt';
  saveLang(); applyLang();
}

document.addEventListener('DOMContentLoaded', () => {
  loadLang();
  const btn = document.getElementById('lang-toggle');
  if (btn) btn.addEventListener('click', switchLang);

  // Smooth scroll
  document.querySelectorAll('a[href^="#"]').forEach(a => {
    a.addEventListener('click', function(e) {
      const href = this.getAttribute('href');
      if (!href || href === '#') return;
      const target = document.querySelector(href);
      if (!target) return;
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
  });
});
